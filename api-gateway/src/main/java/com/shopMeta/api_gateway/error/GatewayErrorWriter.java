package com.shopMeta.api_gateway.error;

import java.time.Instant;
import java.util.LinkedHashMap;
import java.util.Map;

import org.springframework.core.io.buffer.DataBuffer;
import org.springframework.http.HttpStatus;
import org.springframework.http.MediaType;
import org.springframework.http.server.reactive.ServerHttpResponse;
import org.springframework.stereotype.Component;
import org.springframework.web.server.ServerWebExchange;

import com.fasterxml.jackson.core.JsonProcessingException;
import com.fasterxml.jackson.databind.ObjectMapper;
import com.shopMeta.api_gateway.filter.CorrelationIdFilter;

import lombok.RequiredArgsConstructor;
import reactor.core.publisher.Mono;

/**
 * Writes the single gateway error shape (spec 5.3):
 *
 * <pre>
 * { "timestamp", "status", "error", "message", "path", "traceId" }
 * </pre>
 *
 * <p>{@code traceId} is the correlation id generated by {@link CorrelationIdFilter}, which is also
 * returned in the {@code X-Correlation-Id} response header.
 */
@Component
@RequiredArgsConstructor
public class GatewayErrorWriter {

    private final ObjectMapper objectMapper;

    public Mono<Void> write(ServerWebExchange exchange, HttpStatus status, String error, String message) {

        ServerHttpResponse response = exchange.getResponse();
        if (response.isCommitted()) {
            return Mono.empty();
        }

        response.setStatusCode(status);
        response.getHeaders().setContentType(MediaType.APPLICATION_JSON);

        Map<String, Object> body = new LinkedHashMap<>();
        body.put("timestamp", Instant.now().toString());
        body.put("status", status.value());
        body.put("error", error);
        body.put("message", message);
        body.put("path", exchange.getRequest().getURI().getPath());
        body.put("traceId", exchange.getAttributes().get(CorrelationIdFilter.CORRELATION_ID_ATTR));

        byte[] bytes;
        try {
            bytes = objectMapper.writeValueAsBytes(body);
        } catch (JsonProcessingException ex) {
            bytes = ("{\"status\":" + status.value() + ",\"error\":\"" + error + "\"}").getBytes();
        }

        DataBuffer buffer = response.bufferFactory().wrap(bytes);
        return response.writeWith(Mono.just(buffer));
    }

}
